let roomId = "";
let userName = "";
let currentVideoUrl = "";
let rutubeReady = false;

let localState = "paused";
let currentTime = 0;
let currentTimeAt = performance.now();

let suppressPlayerEventsUntil = 0;
let lastCommandAt = 0;
let lastStateVersion = 0;
let roomState = null;
let lastHeartbeat = 0;
let lastReportedSeek = -1;

function randomRoomId() {
  return Math.random().toString(36).slice(2, 8).toUpperCase();
}
function getRoomFromUrl() {
  return new URLSearchParams(location.search).get("room");
}
function normalizeUrl(value) {
  try { return new URL(value.trim()); } catch { return null; }
}
function getEmbedUrl(value) {
  const url = normalizeUrl(value);
  if (!url) return null;
  const host = url.hostname.toLowerCase();

  if (host === "rutube.ru" || host.endsWith(".rutube.ru")) {
    const match = url.pathname.match(/\/(?:video|shorts)\/([a-zA-Z0-9_-]+)/);
    if (match) return `https://rutube.ru/play/embed/${match[1]}/`;
  }
  if (["youtube.com","www.youtube.com","m.youtube.com"].includes(host)) {
    const id = url.searchParams.get("v");
    const shorts = url.pathname.match(/\/shorts\/([^/]+)/);
    if (id) return `https://www.youtube.com/embed/${id}?enablejsapi=1`;
    if (shorts) return `https://www.youtube.com/embed/${shorts[1]}?enablejsapi=1`;
  }
  if (host === "youtu.be") {
    const id = url.pathname.split("/").filter(Boolean)[0];
    if (id) return `https://www.youtube.com/embed/${id}?enablejsapi=1`;
  }
  return url.href;
}
function isRutubeUrl(value) {
  const u = normalizeUrl(value);
  return !!u && /(^|\.)rutube\.ru$/i.test(u.hostname);
}
function setStatus(text) {
  statusEl.textContent = text;
}
function showRoom() {
  startScreen.classList.add("hidden");
  roomScreen.classList.remove("hidden");
  roomLabel.textContent = `Комната ${roomId}`;
}

function loadVideo(value, remote = false) {
  const embed = getEmbedUrl(value);
  if (!embed) {
    setStatus("Неверная ссылка");
    return false;
  }

  currentVideoUrl = value;
  rutubeReady = false;
  localState = "paused";
  currentTime = 0;
  currentTimeAt = performance.now();
  suppressPlayerEventsUntil = performance.now() + 2500;

  videoPlaceholder.classList.add("hidden");
  videoFrame.src = embed;
  setStatus(isRutubeUrl(value) ? "RUTUBE: загрузка..." : "Видео загружается");

  if (!remote) socket.emit("set-video", { roomId, videoUrl: value });
  return true;
}

function rutubeCommand(type, time) {
  if (!videoFrame.contentWindow || !rutubeReady) return;
  const message = { type: `player:${type}`, data: {} };
  if (Number.isFinite(time)) message.data.time = Math.max(0, time);
  videoFrame.contentWindow.postMessage(JSON.stringify(message), "https://rutube.ru");
}

function estimatedTime() {
  if (localState !== "playing") return Math.max(0, currentTime);
  return Math.max(0, currentTime + (performance.now() - currentTimeAt) / 1000);
}

function rememberTime(time, state = localState) {
  currentTime = Math.max(0, Number(time) || 0);
  localState = state;
  currentTimeAt = performance.now();
}

function sendLocalCommand(type, time) {
  if (!roomId || !isRutubeUrl(currentVideoUrl)) return;

  const t = Number.isFinite(time) ? Math.max(0, time) : estimatedTime();
  lastCommandAt = performance.now();

  // Lock out player events generated by the command itself.
  // This is the key part preventing pause -> stale "playing" -> resume loops.
  suppressPlayerEventsUntil = performance.now() + 1800;

  if (type === "pause") {
    rememberTime(t, "paused");
  } else if (type === "play") {
    rememberTime(t, "playing");
  } else if (type === "seek") {
    currentTime = t;
    currentTimeAt = performance.now();
  }

  socket.emit("player-command", {
    roomId,
    command: { type, time: t }
  });
}

function applyAuthoritativeState(state) {
  if (!rutubeReady || !state) return;

  const version = Number(state.stateVersion) || 0;
  if (version && version <= lastStateVersion) return;
  if (version) lastStateVersion = version;

  // Don't re-apply the command on the device that sent it.
  if (state.originId === socket.id) return;

  const serverTime = Math.max(0, Number(state.position) || 0);
  const delay = state.playing && state.serverAt
    ? Math.min(1, Math.max(0, (Date.now() - Number(state.serverAt)) / 1000))
    : 0;
  const target = state.playing ? serverTime + delay : serverTime;

  // Any state coming from the server is authoritative. Ignore all player
  // events caused by applying it for a generous window.
  suppressPlayerEventsUntil = performance.now() + 1800;

  if (!state.playing) {
    // IMPORTANT: pause is sent BEFORE and AFTER the time correction.
    // The second device therefore cannot keep playing at an old position.
    localState = "paused";
    currentTime = target;
    currentTimeAt = performance.now();

    rutubeCommand("pause");
    rutubeCommand("setCurrentTime", target);

    setTimeout(() => {
      rutubeCommand("pause");
      rutubeCommand("setCurrentTime", target);
      rutubeCommand("pause");
    }, 120);

    setTimeout(() => rutubeCommand("pause"), 450);
    setTimeout(() => rutubeCommand("pause"), 1000);

    setStatus("Пауза синхронизирована ⏸");
  } else {
    const local = estimatedTime();
    const drift = Math.abs(target - local);

    localState = "playing";

    if (drift > 1.5) {
      currentTime = target;
      currentTimeAt = performance.now();
      rutubeCommand("setCurrentTime", target);
    }

    rutubeCommand("play");

    setTimeout(() => {
      rutubeCommand("play");
    }, 180);

    setStatus("Воспроизведение синхронизировано ▶");
  }

  setTimeout(() => {
    currentTimeAt = performance.now();
  }, 1000);
}

window.addEventListener("message", event => {
  if (event.origin !== "https://rutube.ru") return;
  if (event.source !== videoFrame.contentWindow) return;

  let data;
  try {
    data = typeof event.data === "string" ? JSON.parse(event.data) : event.data;
  } catch {
    return;
  }
  if (!data || !data.type) return;

  if (data.type === "player:ready") {
    rutubeReady = true;
    setStatus("RUTUBE готов");

    if (roomState) {
      setTimeout(() => {
        const target = Math.max(0, Number(roomState.position) || 0);
        suppressPlayerEventsUntil = performance.now() + 2200;
        localState = roomState.playing ? "playing" : "paused";
        currentTime = target;
        currentTimeAt = performance.now();

        rutubeCommand("setCurrentTime", target);
        if (roomState.playing) {
          rutubeCommand("play");
          setTimeout(() => rutubeCommand("play"), 180);
        } else {
          rutubeCommand("pause");
          setTimeout(() => rutubeCommand("pause"), 150);
        }
      }, 250);
    }
    return;
  }

  if (data.type === "player:changeState") {
    const state = data.data?.state;
    if (!["playing", "paused", "stopped"].includes(state)) return;

    // NEVER let a remote command echo back into the server.
    if (performance.now() < suppressPlayerEventsUntil) return;

    if (state === "playing") {
      localState = "playing";
      currentTimeAt = performance.now();
      sendLocalCommand("play", estimatedTime());
    } else {
      const t = estimatedTime();
      localState = "paused";
      currentTime = t;
      currentTimeAt = performance.now();
      sendLocalCommand("pause", t);
    }
    return;
  }

  if (data.type === "player:currentTime") {
    const time = Number(data.data?.time);
    if (!Number.isFinite(time)) return;

    const now = performance.now();
    const wasPlaying = localState === "playing";
    const expected = estimatedTime();
    const jump = Math.abs(time - expected);

    // Always remember the actual player time.
    currentTime = time;
    currentTimeAt = now;

    if (performance.now() < suppressPlayerEventsUntil) return;

    // Detect a genuine user seek, not normal playback drift.
    if (wasPlaying && jump > 2.0 && now - lastCommandAt > 700) {
      if (Math.abs(time - lastReportedSeek) > 0.5 || now - lastHeartbeat > 1000) {
        lastReportedSeek = time;
        sendLocalCommand("seek", time);
      }
    }
  }
});

createBtn.addEventListener("click", () => {
  userName = nameInput.value.trim() || "Гость";
  roomId = randomRoomId();
  const initialVideo = videoInput.value.trim();
  localStorage.setItem("watchTogetherName", userName);
  history.replaceState({}, "", `?room=${roomId}`);
  joinRoom(roomId, userName);
  if (initialVideo) loadVideo(initialVideo);
});

changeVideoBtn.addEventListener("click", () => {
  const value = changeVideoInput.value.trim();
  if (value) loadVideo(value);
});
changeVideoInput.addEventListener("keydown", e => {
  if (e.key === "Enter") {
    e.preventDefault();
    changeVideoBtn.click();
  }
});
copyBtn.addEventListener("click", async () => {
  const link = location.href;
  try {
    await navigator.clipboard.writeText(link);
    copyBtn.textContent = "Скопировано ✓";
    setTimeout(() => copyBtn.textContent = "Скопировать ссылку", 1800);
  } catch {
    prompt("Скопируйте ссылку:", link);
  }
});
chatForm.addEventListener("submit", e => {
  e.preventDefault();
  const text = chatInput.value.trim();
  if (!text) return;
  socket.emit("chat-message", { roomId, text });
  chatInput.value = "";
  chatInput.focus();
});

function joinRoom(id, name) {
  roomId = String(id || "").trim().toUpperCase();
  userName = String(name || "Гость").trim() || "Гость";
  if (!roomId) return;
  showRoom();
  socket.emit("join-room", { roomId, name: userName });
}

socket.on("room-state", state => {
  roomState = state;
  lastStateVersion = Number(state.stateVersion) || 0;
  renderMessages(state.messages);

  if (state.videoUrl) {
    loadVideo(state.videoUrl, true);
  }
});

socket.on("remote-video", ({ videoUrl }) => {
  if (videoUrl) loadVideo(videoUrl, true);
});

socket.on("authoritative-state", applyAuthoritativeState);
socket.on("chat-message", addMessage);
socket.on("users", count => {
  usersLabel.textContent = `👤 ${count}`;
});

function addMessage(message) {
  const item = document.createElement("div");
  item.className = "message";
  const name = document.createElement("strong");
  name.textContent = message.name || "Гость";
  const text = document.createElement("span");
  text.textContent = message.text || "";
  item.append(name, text);
  messagesEl.appendChild(item);
  messagesEl.scrollTop = messagesEl.scrollHeight;
}
function renderMessages(messages) {
  messagesEl.innerHTML = "";
  (messages || []).forEach(addMessage);
}

// Only the controller sends a lightweight position heartbeat while playing.
// The server never changes the room from paused to playing from a heartbeat.
setInterval(() => {
  if (!roomId || !isRutubeUrl(currentVideoUrl) || !rutubeReady) return;
  if (localState !== "playing") return;
  if (performance.now() - suppressPlayerEventsUntil < 0) return;
  if (performance.now() - lastHeartbeat < 900) return;

  lastHeartbeat = performance.now();
  socket.emit("sync-position", {
    roomId,
    time: estimatedTime()
  });
}, 300);

const existingRoom = getRoomFromUrl();
if (existingRoom) {
  const savedName = localStorage.getItem("watchTogetherName") || "";
  const name = savedName || prompt("Введите ваше имя:") || "Гость";
  localStorage.setItem("watchTogetherName", name);
  joinRoom(existingRoom, name);
}
